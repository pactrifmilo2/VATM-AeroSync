SET PAGESIZE 300 FEEDBACK OFF LINESIZE 400 TRIMOUT ON TRIMSPOOL ON
COLUMN LINE_FMT FORMAT A(390)
PROMPT ===IMPORTS 6517===
SELECT 'IMPORT|' || pi.ID || '|job=' || pi.SYNC_JOB_ID || '|norm=' || pi.NORMALIZED_PERMIT_ID ||
       '|master=' || pi.TARGET_MASTER_ID || '|perm=' || pi.TARGET_PERM_ID ||
       '|details=' || pi.DETAIL_COUNT || '|status=' || pi.STATUS ||
       '|at=' || TO_CHAR(pi.UPDATED_AT,'YYYY-MM-DD HH24:MI:SS') AS LINE_FMT
  FROM PERMIT_IMPORTS pi
 WHERE pi.NORMALIZED_PERMIT_ID LIKE '%6517%'
 ORDER BY pi.ID DESC;
PROMPT ===FILE_RECORDS 6517===
SELECT 'FR|' || fr.ID || '|job=' || fr.SYNC_JOB_ID || '|name=' || fr.ORIGINAL_FILE_NAME AS LINE_FMT
  FROM FILE_RECORDS fr
 WHERE fr.ORIGINAL_FILE_NAME LIKE '%6517%'
 ORDER BY fr.ID DESC;
EXIT;
