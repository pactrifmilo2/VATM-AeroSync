class NoRevisionReplacementGatewayTest {
    private AtfmDatabaseProperties properties;
    private JdbcAtfmScheduleGateway gateway;

    @BeforeEach
    void setup() throws Exception {
        properties = new AtfmDatabaseProperties();
        properties.setUrl("jdbc:h2:mem:no-replacement-" + System.nanoTime() + ";MODE=Oracle;DB_CLOSE_DELAY=-1");
        properties.setUsername("sa"); properties.setPassword("");
        gateway = new JdbcAtfmScheduleGateway(properties, new AtfmAirportCodeResolver());
        try (var connection = connection(); var sql = connection.createStatement()) {
            sql.execute("CREATE TABLE M_FPAUTHOR (AUTHOR_CODE VARCHAR2(20))");
            sql.execute("CREATE TABLE M_OPER (OPER_ICAO VARCHAR2(20))");
            sql.execute("CREATE TABLE M_FLY_PURPOSE (PURPOSE_CODE VARCHAR2(20))");
            sql.execute("CREATE TABLE M_CRAFT_TYPE (CRAFT_ID NUMBER, MA VARCHAR2(4), SOHIEU VARCHAR2(3), SOHIEU2 VARCHAR2(20), TAITRONG NUMBER)");
            sql.execute("CREATE TABLE M_AERO (AE_CODE VARCHAR2(4), AE_IATA VARCHAR2(3))");
            sql.execute("INSERT INTO M_AERO (AE_CODE) VALUES ('VHHH'), ('LFPB'), ('LFLL')");
            sql.execute("INSERT INTO M_FPAUTHOR VALUES ('CHK')");
            sql.execute("INSERT INTO M_OPER VALUES ('TBJ')");
            sql.execute("INSERT INTO M_FLY_PURPOSE VALUES ('VIP')");
            sql.execute("INSERT INTO M_CRAFT_TYPE (CRAFT_ID) VALUES (321)");
            sql.execute("""
                    CREATE TABLE T_PERMMASTER_NO (
                      ID NUMBER PRIMARY KEY, PERM_ID NUMBER, PERMNBR_ID VARCHAR2(100), OPER_ID VARCHAR2(20),
                      REFERENCE VARCHAR2(4000), PERMCONTENT VARCHAR2(4000), PERMCONTENT1 CLOB,
                      LASTMODIFY TIMESTAMP, LASTUSER VARCHAR2(50))
                    """);
            sql.execute("""
                    CREATE TABLE T_PERMDETAIL_NO (
                      ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      PERM_ID NUMBER, CRAFT_ID NUMBER, MTOW NUMBER, DAYSFLIGHT VARCHAR2(200),
                      FLIGHTNBR VARCHAR2(30), REGISTRATION VARCHAR2(100), FROM_AIRP VARCHAR2(10), TO_AIRP VARCHAR2(10),
                      ETD VARCHAR2(10), ETA VARCHAR2(10), VIA VARCHAR2(4000), STATUS VARCHAR2(20),
                      LASTMODIFY TIMESTAMP, LASTUSER VARCHAR2(50), PURPOSE_ID VARCHAR2(20), MAX_DATE DATE, REMARK VARCHAR2(4000))
                    """);
            sql.execute("CREATE TABLE T_PERMMASTER_NO_BACKUP AS SELECT * FROM T_PERMMASTER_NO WHERE 1 = 0");
            sql.execute("CREATE TABLE T_PERMDETAIL_NO_BACKUP AS SELECT * FROM T_PERMDETAIL_NO WHERE 1 = 0");
            sql.execute("""
                    INSERT INTO T_PERMMASTER_NO VALUES (10,20,'O/F 06916/CHK/2026','TBJ',
                      'EM 24092026','BASE','BASE',CURRENT_TIMESTAMP,'ORIGINAL')
                    """);
        }
        insert(20, old());
    }

    @Test
    void deletesOldIdAndInsertsChangedCallsignDateSectorAndTimesLeavingOthersUntouched() throws Exception {
        insert(20, flight("TBJ90", 28, "LFPB", "1800", "0655+", "W9"));
        insert(20, flight("TBJ90", 26, "LFPB", "1700", "0655+", "W9"));
        insert(99, old());
        List<String> before = rows();
        assertThat(gateway.update(permit(List.of(old()), List.of(revised()))).detailCount()).isEqualTo(1);
        List<String> after = rows();
        assertThat(after).hasSize(4);
        assertThat(after).doesNotContain(before.getFirst());
        assertThat(after).contains(before.get(1), before.get(2), before.get(3));
        assertThat(after).anySatisfy(row -> assertThat(row).contains("TBJ91", "27-SEP-2026", "LFLL", "2000", "0830+", "VIP", "321"));
        try (var connection = connection();
             var master = connection.createStatement().executeQuery(
                     "SELECT PERMNBR_ID, REFERENCE FROM T_PERMMASTER_NO_BACKUP WHERE ID=10 AND PERM_ID=20");
             var details = connection.createStatement().executeQuery(
                     "SELECT COUNT(*) TOTAL, MAX(FLIGHTNBR) FLIGHTNBR, MAX(TO_AIRP) TO_AIRP "
                             + "FROM T_PERMDETAIL_NO_BACKUP WHERE PERM_ID=20")) {
            assertThat(master.next()).isTrue();
            assertThat(master.getString("PERMNBR_ID")).isEqualTo("O/F 06916/CHK/2026");
            assertThat(master.getString("REFERENCE")).isEqualTo("EM 24092026");
            assertThat(details.next()).isTrue();
            assertThat(details.getInt("TOTAL")).isEqualTo(3);
            assertThat(details.getString("FLIGHTNBR")).isEqualTo("TBJ90");
            assertThat(details.getString("TO_AIRP")).isEqualTo("LFPB");
        }
        assertThat(gateway.update(permit(List.of(old()), List.of(revised()))).detailCount()).isZero();
        assertThat(rows()).containsExactlyElementsOf(after);
    }

    @Test
    void missingOldNeverFallsBackToCallsignOrCreatesRows() throws Exception {
        var before = rows();
        var wrongOld = flight("TBJ90", 25, "LFPB", "1800", "0655+", "W1");
        assertThatThrownBy(() -> gateway.update(permit(List.of(wrongOld), List.of(revised()))))
                .hasMessageContaining("OLD schedule is missing");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void duplicateOldFailsBeforeDelete() throws Exception {
        insert(20, old()); var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()), List.of(revised()))))
                .hasMessageContaining("ambiguous");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void insertFailureRollsBackDeleteAndMasterHistory() throws Exception {
        try (var connection = connection(); var sql = connection.createStatement()) {
            sql.execute("ALTER TABLE T_PERMDETAIL_NO ADD CONSTRAINT reject_new CHECK (TO_AIRP <> 'LFLL')");
        }
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()), List.of(revised())))).isInstanceOf(IllegalStateException.class);
        assertThat(rows()).containsExactlyElementsOf(before);
        try (var connection = connection();
             var rows = connection.createStatement().executeQuery(
                     "SELECT COUNT(*) FROM T_PERMDETAIL_NO_BACKUP WHERE PERM_ID=20")) {
            rows.next();
            assertThat(rows.getInt(1)).isZero();
        }
        try (var connection = connection(); var row = connection.createStatement().executeQuery("SELECT PERMCONTENT1 FROM T_PERMMASTER_NO WHERE ID=10")) {
            row.next(); assertThat(row.getString(1)).isEqualTo("BASE");
        }
    }

    @Test
    void missingMasterDoesNotCreateOne() throws Exception {
        try (var connection = connection()) { connection.createStatement().execute("DELETE FROM T_PERMMASTER_NO"); }
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()), List.of(revised()))))
                .hasMessageContaining("refusing to create");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void existingNewCannotCauseCoordinatorToSkipResidualOld() throws Exception {
        insert(20, revised());
        var permit = permit(List.of(old()), List.of(revised()));
        assertThat(gateway.findExisting(permit).orElseThrow().matchesExpectedPermit()).isFalse();
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit)).hasMessageContaining("already exists outside");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void replacesTwoOldRowsAtomicallyWithDifferentNewCount() throws Exception {
        var old2 = flight("TBJ92", 26, "LFPB", "1900", "0655+", "W1"); insert(20, old2);
        var permit = permit(List.of(old(), old2), List.of(revised()));
        assertThat(gateway.update(permit).detailCount()).isOne();
        assertThat(rows()).hasSize(1);
    }

    @Test
    void noOpRevisionCanBeRetriedWithoutReinserting() throws Exception {
        var same = old().withRemark("EM 25092026 R(1)");
        var permit = permit(List.of(old()), List.of(same));
        assertThat(gateway.update(permit).detailCount()).isOne();
        var after = rows();
        assertThat(gateway.update(permit).detailCount()).isZero();
        assertThat(rows()).containsExactlyElementsOf(after);
    }

    @Test
    void requiresOldTableAndRejectsMultiDatePhysicalRows() throws Exception {
        assertThatThrownBy(() -> gateway.update(permit(List.of(), List.of(revised())))).hasMessageContaining("OLD schedule");
        try (var connection = connection()) {
            connection.createStatement().execute("UPDATE T_PERMDETAIL_NO SET DAYSFLIGHT='26-SEP-2026,28-SEP-2026'");
        }
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()), List.of(revised())))).hasMessageContaining("multiple stored dates");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void partialOldMatchRollsBackWithoutAnyDeletion() throws Exception {
        var missing = flight("TBJ99", 26, "LFPB", "1800", "0655+", "W1");
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old(), missing), List.of(revised()))))
                .hasMessageContaining("partially applied");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void rejectsDuplicateNewRowsBeforeDeletingOld() throws Exception {
        var before = rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()), List.of(revised(), revised()))))
                .hasMessageContaining("NEW table repeats");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void unchangedPurposeAndCraftCannotDriftBetweenReconcileAndTransaction() throws Exception {
        try (var connection=connection()) {
            connection.createStatement().execute("UPDATE T_PERMDETAIL_NO SET PURPOSE_ID='CAR'");
        }
        var before=rows();
        assertThatThrownBy(() -> gateway.update(permit(List.of(old()),List.of(revised()))))
                .hasMessageContaining("attributes changed");
        assertThat(rows()).containsExactlyElementsOf(before);
    }

    @Test
    void realDocumentCanDeleteOldAndInsertNewThroughReconcileAndGateway() throws Exception {
        String sample=System.getProperty("permit.of6916.sample");
        org.junit.jupiter.api.Assumptions.assumeTrue(sample!=null,"Set permit.of6916.sample for real Word end-to-end test");
        var path = java.nio.file.Path.of(sample);
        var parsed = new vatm.aerosync.worker.pipeline.DocxSchedulePermitParser().parse(path, path.getFileName().toString());
        var context = new vatm.aerosync.worker.model.ProcessingContext(new vatm.aerosync.common.dto.FileIngestedEvent(
                1L,path.toString(),"hash",vatm.aerosync.common.enums.FileSourceType.EMAIL,false));
        context.setFilePath(path); context.setSchedulePermit(parsed);
        new vatm.aerosync.worker.pipeline.RevisionReconciliationStep(gateway).reconcile(context);
        assertThat(context.getSchedulePermit().operatorId()).isEqualTo("TBJ");
        var replacement=context.getSchedulePermit().flights().getFirst();
        assertThat(replacement.purposeId()).isEqualTo("VIP");
        assertThat(replacement.craftId()).isEqualTo(321);
        assertThat(replacement.toAirport()).isEqualTo("LFLL");
        assertThat(replacement.etd()).isEqualTo("2000");
        assertThat(replacement.eta()).isEqualTo("0830+");
        assertThat(replacement.via()).isEqualTo("R474/W21/B214");
        var before=rows();
        var permit=context.getSchedulePermit().withReference("EM 24092026");
        assertThat(gateway.update(permit).detailCount()).isOne();
        var after=rows();assertThat(after).hasSize(1).doesNotContain(before.getFirst());
        assertThat(after.getFirst()).contains("LFLL","2000","0830+","R474/W21/B214","VIP","321");
        // Re-read original Word like a crashed worker/new job; NEW is the baseline now.
        context.setSchedulePermit(parsed);
        new vatm.aerosync.worker.pipeline.RevisionReconciliationStep(gateway).reconcile(context);
        assertThat(gateway.update(context.getSchedulePermit().withReference("EM 24092026")).detailCount()).isZero();
        assertThat(rows()).containsExactlyElementsOf(after);
    }

    @Test
    void purposeOnlyReplacementRetainsScheduleAndCanBeRetried() throws Exception {
        try (var connection=connection()) {
            connection.createStatement().execute("INSERT INTO M_FLY_PURPOSE VALUES ('CAR')");
        }
        var replacement = old().withPurposeId("CAR").withRemark("CAR EM 25092026 R(1)");
        var permit = permit(List.of(old()), List.of(replacement));
        assertThat(gateway.update(permit).detailCount()).isOne();
        var after = rows();
        assertThat(gateway.update(permit).detailCount()).isZero();
        assertThat(rows()).containsExactlyElementsOf(after);
    }

    private ScheduleFlight old() { return flight("TBJ90", 26, "LFPB", "1800", "0655+", "W1"); }
    private ScheduleFlight revised() { return flight("TBJ91", 27, "LFLL", "2000", "0830+", "A1/W2").withRemark("EM 25092026 R(1)"); }
    private ScheduleFlight flight(String call, int day, String to, String etd, String eta, String via) {
        LocalDate date = LocalDate.of(2026, 9, day);
        char[] flags = "0000000".toCharArray(); flags[date.getDayOfWeek().getValue()-1] = (char) ('0'+date.getDayOfWeek().getValue());
        return new ScheduleFlight("VIP", 321, BigDecimal.TEN, call, null, new String(flags), "VHHH", to,
                etd, eta, via, date, date, null);
    }
    private SchedulePermit permit(List<ScheduleFlight> old, List<ScheduleFlight> revised) {
        return new SchedulePermit("OF-6916/9/2026VN/REV1", "O/F 06916/CHK/2026", "6916", "CHK", "O/F", "A", null,
                LocalDate.of(2026, 9, 25), "TBJ", "EM 25092026", 72, "TAG", "NO", false, false, false,
                "REV1 REPLACEMENT CONTENT", revised, old);
    }
    private Connection connection() throws SQLException { return DriverManager.getConnection(properties.getUrl(), "sa", ""); }
    private void insert(long permId, ScheduleFlight f) throws Exception {
        try (var c = connection(); var s = c.prepareStatement("INSERT INTO T_PERMDETAIL_NO (PERM_ID,CRAFT_ID,MTOW,DAYSFLIGHT,FLIGHTNBR,FROM_AIRP,TO_AIRP,ETD,ETA,VIA,PURPOSE_ID,MAX_DATE) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)")) {
            s.setLong(1,permId);s.setLong(2,f.craftId());s.setBigDecimal(3,f.mtow());
            s.setString(4,f.beginDate().format(java.time.format.DateTimeFormatter.ofPattern("dd-MMM-uuuu",java.util.Locale.ENGLISH)).toUpperCase(java.util.Locale.ROOT));
            s.setString(5,f.flightNumber());s.setString(6,f.fromAirport());s.setString(7,f.toAirport());s.setString(8,f.etd());s.setString(9,f.eta());s.setString(10,f.via());s.setString(11,f.purposeId());s.setDate(12,Date.valueOf(f.endDate()));s.executeUpdate();
        }
    }
    private List<String> rows() throws Exception {
        var values = new ArrayList<String>();
        try (var c=connection();var r=c.createStatement().executeQuery("SELECT ID,PERM_ID,FLIGHTNBR,DAYSFLIGHT,FROM_AIRP,TO_AIRP,ETD,ETA,CRAFT_ID,PURPOSE_ID,VIA FROM T_PERMDETAIL_NO ORDER BY ID")) {
            while(r.next()) {var line=new ArrayList<String>();for(int i=1;i<=11;i++)line.add(r.getString(i));values.add(String.join("|",line));}
        }
        return values;
    }
}
